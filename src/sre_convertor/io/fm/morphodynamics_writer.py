from __future__ import annotations

from pathlib import Path

from ...models import CrossSectionLocation, LayerCompositionSample, MorphodynamicsSummary, NetworkModel


COMPOSITION_FILE_NAME = "mor_composition.ini"
MIN_VOLUME_FRACTION = 1.0e-6


def write_morphodynamics_files(
    target_dir: Path,
    summary: MorphodynamicsSummary,
    network: NetworkModel | None = None,
    cross_section_locations: tuple[CrossSectionLocation, ...] | None = None,
) -> tuple[Path, Path, Path, Path]:
    target_dir.mkdir(parents=True, exist_ok=True)

    mor_path = target_dir / "mor.mor"
    sed_path = target_dir / "sed.sed"
    composition_path = target_dir / COMPOSITION_FILE_NAME
    bed_comp_path = composition_path

    for stale_name in ("mor.composition.ini", "mor.ini"):
        stale_path = target_dir / stale_name
        if stale_path != composition_path and stale_path.exists():
            stale_path.unlink()

    fractions = summary.sediment_fractions_d50_m
    if not fractions:
        fallback = summary.representative_d50_m or 0.001
        fractions = (fallback,)
    layer_count = summary.underlayer_count or 1
    layer_thickness_m = summary.underlayer_thickness_m or 0.5
    max_underlayers = max(layer_count - 1, 1)
    underlayer_type = 2 if layer_count > 1 else 1

    mor_content = f"""[MorphologyFileInformation]
   FileCreatedBy    = sre_convertor
   FileCreationDate = autogenerated
   FileVersion      = 02.00

[Morphology]
   MorFac           = 1.0
   MorStt           = 0.0
   Thresh           = 1.0
   BedUpd           = 1
   CmpUpd           = 1
   NeuBcMud         = 0
   NeuBcSand        = 0

[Output]
   Dm               = true
   Dg               = true
   Frac             = true

[Underlayer]
    IUnderLyr        = {underlayer_type}
    ExchLyr          = false
    IniComp          = mor_composition.ini
    TTLForm          = 1
    ThTrLyr          = 1.0
    MxNULyr          = {max_underlayers}
    ThUnLyr          = {layer_thickness_m:.7e}
"""

    sed_blocks: list[str] = []
    for idx, d50 in enumerate(fractions, start=1):
        sed_blocks.extend(
            [
                "[Sediment]",
                f"   Name             = #Sediment{idx}#",
                "   SedTyp           = bedload",
                "   IniSedThick      = 1.0000000e+000",
                "   RhoSol           = 2.6500000e+003",
                "   TraFrm           = 1",
                "   CDryB            = 1.5900000e+003",
                f"   SedDia           = {d50:.7e}",
                "   ACal             = 1.0000000e+000",
                "   RouKs            = 0.000",
                "   SusFac           = 0.000",
                "",
            ]
        )

    sed_content = """[SedimentFileInformation]
   FileCreatedBy    = sre_convertor
   FileCreationDate = autogenerated
   FileVersion      = 02.00

[SedimentOverall]
   Cref             = 1.6000000e+003
""" + "\n".join(sed_blocks)

    composition_lines: list[str] = [
        "[BedCompositionFileInformation]",
        "FileVersion     = 01.00",
        "FileCreatedBy   = sre_convertor",
        "FileCreationDate= autogenerated",
        "",
        "[Layer]",
        "Type = volume fraction",
    ]

    # Generate xyz files if we have spatial data
    if network and cross_section_locations:
        gsd_dir = target_dir / "gsd_ini_str"
        gsd_dir.mkdir(parents=True, exist_ok=True)
        for stale_path in gsd_dir.glob("lyr*_*.xyz"):
            stale_path.unlink()

        coordinates: list[tuple[CrossSectionLocation, float, float]] = []
        for cs_location in cross_section_locations:
            xy = _chainage_to_xy(network, cs_location.branch_id, cs_location.chainage)
            if xy:
                x, y = xy
                coordinates.append((cs_location, x, y))
        layer_samples_by_branch = _group_layer_composition(summary.layer_composition)

        for layer_idx in range(1, layer_count + 1):
            if layer_idx > 1:
                composition_lines.extend(["", "[Layer]", "Type = volume fraction"])

            layer_prefix = f"lyr{layer_idx:02d}"
            thk_xyz_lines = [f"{x:.15E} {y:.15E} {layer_thickness_m:.15E}" for _, x, y in coordinates]
            if thk_xyz_lines:
                thk_path = gsd_dir / f"{layer_prefix}_thk.xyz"
                thk_path.write_text("\n".join(thk_xyz_lines) + "\n", encoding="utf-8")
                composition_lines.append(f"Thick = gsd_ini_str/{layer_prefix}_thk.xyz")

            for fraction_idx in range(1, len(fractions) + 1):
                xyz_lines: list[str] = []
                for cs_location, x, y in coordinates:
                    weight = _get_layer_fraction_weights(
                        summary,
                        layer_samples_by_branch,
                        cs_location.branch_id,
                        cs_location.chainage,
                        layer_idx,
                        len(fractions),
                    )[fraction_idx - 1]
                    xyz_lines.append(f"{x:.15E} {y:.15E} {weight:.15E}")

                if xyz_lines:
                    xyz_path = gsd_dir / f"{layer_prefix}_frac{fraction_idx:02d}.xyz"
                    xyz_path.write_text("\n".join(xyz_lines) + "\n", encoding="utf-8")
                    composition_lines.append(f"Fraction{fraction_idx} = gsd_ini_str/{layer_prefix}_frac{fraction_idx:02d}.xyz")

    composition_content = "\n".join(composition_lines)

    mor_path.write_text(mor_content, encoding="utf-8")
    sed_path.write_text(sed_content, encoding="utf-8")
    composition_path.write_text(composition_content, encoding="utf-8")

    return mor_path, sed_path, composition_path, bed_comp_path


def _chainage_to_xy(network: NetworkModel, branch_id: str, chainage: float) -> tuple[float, float] | None:
    """Convert branch/chainage to xy coordinates by linear interpolation between nodes."""
    branch = next((b for b in network.branches if b.id == branch_id), None)
    if not branch:
        return None

    from_node = next((n for n in network.nodes if n.id == branch.from_node_id), None)
    to_node = next((n for n in network.nodes if n.id == branch.to_node_id), None)

    if not from_node or not to_node or branch.length == 0:
        return None

    # Linear interpolation
    ratio = chainage / branch.length
    x = from_node.x + (to_node.x - from_node.x) * ratio
    y = from_node.y + (to_node.y - from_node.y) * ratio
    return x, y


def _get_fraction_weights(summary: MorphodynamicsSummary, branch_id: str, fraction_count: int) -> tuple[float, ...]:
    for bid, weights in summary.branch_composition:
        if bid == branch_id:
            padded = tuple(weights[:fraction_count]) + (0.0,) * max(0, fraction_count - len(weights))
            return _normalize_volume_fractions(padded)
    return _normalize_volume_fractions((1.0,) + (0.0,) * max(0, fraction_count - 1))


def _group_layer_composition(
    samples: tuple[LayerCompositionSample, ...],
) -> dict[str, tuple[LayerCompositionSample, ...]]:
    grouped: dict[str, list[LayerCompositionSample]] = {}
    for sample in samples:
        grouped.setdefault(sample.branch_id, []).append(sample)
    return {branch_id: tuple(sorted(items, key=lambda item: item.chainage)) for branch_id, items in grouped.items()}


def _get_layer_fraction_weights(
    summary: MorphodynamicsSummary,
    samples_by_branch: dict[str, tuple[LayerCompositionSample, ...]],
    branch_id: str,
    chainage: float,
    layer_idx: int,
    fraction_count: int,
) -> tuple[float, ...]:
    samples = samples_by_branch.get(branch_id, tuple())
    if not samples:
        return _get_fraction_weights(summary, branch_id, fraction_count)

    layer_position = layer_idx - 1
    if chainage <= samples[0].chainage:
        return _sample_layer_weights(samples[0], layer_position, fraction_count, summary, branch_id)
    if chainage >= samples[-1].chainage:
        return _sample_layer_weights(samples[-1], layer_position, fraction_count, summary, branch_id)

    for lower, upper in zip(samples, samples[1:]):
        if lower.chainage <= chainage <= upper.chainage:
            lower_weights = _sample_layer_weights(lower, layer_position, fraction_count, summary, branch_id)
            upper_weights = _sample_layer_weights(upper, layer_position, fraction_count, summary, branch_id)
            if len(lower_weights) != len(upper_weights):
                nearest = lower if abs(chainage - lower.chainage) <= abs(chainage - upper.chainage) else upper
                return _sample_layer_weights(nearest, layer_position, fraction_count, summary, branch_id)

            span = upper.chainage - lower.chainage
            if span <= 0.0:
                return lower_weights
            ratio = (chainage - lower.chainage) / span
            interpolated = tuple(
                lower_weights[idx] + (upper_weights[idx] - lower_weights[idx]) * ratio for idx in range(fraction_count)
            )
            return _normalize_volume_fractions(interpolated)

    return _get_fraction_weights(summary, branch_id, fraction_count)


def _sample_layer_weights(
    sample: LayerCompositionSample,
    layer_position: int,
    fraction_count: int,
    summary: MorphodynamicsSummary,
    branch_id: str,
) -> tuple[float, ...]:
    if layer_position < len(sample.layer_weights):
        weights = sample.layer_weights[layer_position]
        if weights:
            padded = tuple(weights[:fraction_count]) + (0.0,) * max(0, fraction_count - len(weights))
            return _normalize_volume_fractions(padded)
    return _get_fraction_weights(summary, branch_id, fraction_count)


def _normalize_volume_fractions(weights: tuple[float, ...]) -> tuple[float, ...]:
    if not weights:
        return tuple()

    clipped = tuple(max(MIN_VOLUME_FRACTION, weight) for weight in weights)
    total = sum(clipped)
    return tuple(weight / total for weight in clipped)
